  const text = String(sectionName || "").toLowerCase();
  if (text.includes("hidro")) return ["Prueba hidráulica 90 PSI / 24h cargada", "Fotos antes de tapar tubería", "Pendientes y registros verificados", "Bitácora sin observaciones abiertas"];
